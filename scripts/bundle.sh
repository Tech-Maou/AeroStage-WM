#!/bin/bash
# Builds "build/AeroStage WM.app" with SwiftPM only (no Xcode needed) and signs it.
# Mirrors what xcode/project.yml produces for the Release configuration.
# Signs with the certificate "AeroStage Dev" (or $AEROSTAGE_SIGN_IDENTITY), otherwise ad-hoc.
#
# Usage: scripts/bundle.sh [version]
#   version defaults to the latest v* tag reachable from HEAD, without the leading "v".
set -euo pipefail
cd "$(dirname "$0")/.."

APP_NAME="AeroStage WM"
BUNDLE_ID="io.github.tech-maou.AeroStageWM"
CLI_NAME="aerostage-wm"
VERSION="${1:-$(git describe --tags --abbrev=0 --match 'v*' | sed 's/^v//')}"

# Stamp version and git hash into the generated sources (as generate.sh does for
# releases) and restore the committed placeholders afterwards.
GENERATED=(Sources/Common/versionGenerated.swift Sources/Common/gitHashGenerated.swift)
BACKUP="$(mktemp -d)"
for f in "${GENERATED[@]}"; do cp "$f" "$BACKUP/"; done
restore() { for f in "${GENERATED[@]}"; do cp "$BACKUP/$(basename "$f")" "$f"; done; rm -rf "$BACKUP"; }
trap restore EXIT

cat > Sources/Common/versionGenerated.swift <<EOF
// FILE IS GENERATED BY generate.sh
public let aeroSpaceAppVersion = "$VERSION"
EOF
cat > Sources/Common/gitHashGenerated.swift <<EOF
// FILE IS GENERATED BY generate.sh
public let gitHash = "$(git rev-parse HEAD)"
public let gitShortHash = "$(git rev-parse --short HEAD)"
EOF

swift build -c release --product AeroSpaceApp
swift build -c release --product "$CLI_NAME"
BIN="$(swift build -c release --show-bin-path)"

APP="build/$APP_NAME.app"
rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources/bin"
cp "$BIN/AeroSpaceApp" "$APP/Contents/MacOS/$APP_NAME"
cp "$BIN/$CLI_NAME" "$APP/Contents/Resources/bin/$CLI_NAME"
cp docs/config-examples/default-config.toml "$APP/Contents/Resources/default-config.toml"
printf 'APPL????' > "$APP/Contents/PkgInfo"

# The asset catalog needs actool (Xcode). Build the app icon with iconutil instead.
# AeroStage WM has its own icon; AeroSpace's icon is not used.
ICON_SRC=resources/aerostage-wm/icon.png
ICONSET="$(mktemp -d)/AppIcon.iconset"
mkdir -p "$ICONSET"
for size in 16 32 128 256 512; do
    sips -z "$size" "$size" "$ICON_SRC" --out "$ICONSET/icon_${size}x${size}.png" > /dev/null
    sips -z $((size * 2)) $((size * 2)) "$ICON_SRC" --out "$ICONSET/icon_${size}x${size}@2x.png" > /dev/null
done
iconutil -c icns "$ICONSET" -o "$APP/Contents/Resources/AppIcon.icns"
rm -rf "$(dirname "$ICONSET")"

cat > "$APP/Contents/Info.plist" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
	<key>CFBundleDevelopmentRegion</key>
	<string>en</string>
	<key>CFBundleExecutable</key>
	<string>$APP_NAME</string>
	<key>CFBundleIconFile</key>
	<string>AppIcon</string>
	<key>CFBundleIdentifier</key>
	<string>$BUNDLE_ID</string>
	<key>CFBundleInfoDictionaryVersion</key>
	<string>6.0</string>
	<key>CFBundleName</key>
	<string>$APP_NAME</string>
	<key>CFBundleDisplayName</key>
	<string>$APP_NAME</string>
	<key>CFBundlePackageType</key>
	<string>APPL</string>
	<key>CFBundleShortVersionString</key>
	<string>$VERSION</string>
	<key>CFBundleVersion</key>
	<string>1</string>
	<key>LSMinimumSystemVersion</key>
	<string>13.0</string>
	<key>LSUIElement</key>
	<true/>
	<key>NSPrincipalClass</key>
	<string>NSApplication</string>
</dict>
</plist>
EOF
plutil -lint "$APP/Contents/Info.plist" > /dev/null

# Signing identity: $AEROSTAGE_SIGN_IDENTITY, else "AeroStage Release" (long-lived, used for
# releases so macOS permissions survive updates), else "AeroStage Dev", else ad-hoc.
IDENTITY="${AEROSTAGE_SIGN_IDENTITY:-}"
if [[ -z "$IDENTITY" ]]; then
    for candidate in "AeroStage Release" "AeroStage Dev"; do
        if security find-identity -p codesigning | grep -q "\"$candidate\""; then
            IDENTITY="$candidate"
            break
        fi
    done
fi
if [[ -z "$IDENTITY" ]] || ! security find-identity -p codesigning | grep -q "\"$IDENTITY\""; then
    echo "No code signing certificate found, signing ad-hoc" >&2
    IDENTITY="-"
fi
# Nested code first, then the app itself.
codesign --force --sign "$IDENTITY" --identifier "$BUNDLE_ID.cli" "$APP/Contents/Resources/bin/$CLI_NAME"
codesign --force --sign "$IDENTITY" --entitlements resources/AeroSpace.entitlements "$APP"
codesign --verify --strict "$APP"
echo "Built: $APP (version $VERSION, signed: $IDENTITY)"
